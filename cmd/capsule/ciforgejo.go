// Pinned versions of the security gates. Bump them deliberately (Renovate can
// do it: the versions live in the `env:` block of the generated ci.yml).
const (
	forgejoGitleaksVersion = "8.21.2"
	forgejoSemgrepVersion  = "1.97.0"
	forgejoOSVVersion      = "1.9.2"
	forgejoTrivyVersion    = "0.58.1"
)

type forgejoFiles struct {
	CI     string
	Deploy string
}

func generateForgejo(st ciStack, o ciOptions) forgejoFiles {
	var c strings.Builder
	c.WriteString("# Generated by `capsule ci init --provider forgejo`. Syntax compatible with GitHub Actions.\n")
	c.WriteString("# Gates: secrets (gitleaks), quality (lint/types/tests), SAST (semgrep), dependencies (osv-scanner),\n")
	c.WriteString("# filesystem/IaC (trivy). All tool versions are PINNED in `env:`; bump them on purpose (Renovate can).\n")
	c.WriteString("# NOTE: CodeQL and Dependabot do not exist on Forgejo. Semgrep (SAST) and Renovate (dependency\n")
	c.WriteString("# update PRs, run it as a separate bot) replace them.\n")
	fmt.Fprintf(&c, "name: CI\n\non:\n  push:\n    branches: [%s]\n  pull_request:\n    branches: [%s]\n  workflow_dispatch:\n\n", o.Branch, o.Branch)
	c.WriteString("env:\n")
	fmt.Fprintf(&c, "  GITLEAKS_VERSION: \"%s\"   # https://github.com/gitleaks/gitleaks/releases\n", forgejoGitleaksVersion)
	fmt.Fprintf(&c, "  SEMGREP_VERSION: \"%s\"    # https://pypi.org/project/semgrep/\n", forgejoSemgrepVersion)
	fmt.Fprintf(&c, "  OSV_SCANNER_VERSION: \"%s\"  # https://github.com/google/osv-scanner/releases\n", forgejoOSVVersion)
	fmt.Fprintf(&c, "  TRIVY_VERSION: \"%s\"      # https://github.com/aquasecurity/trivy/releases\n\n", forgejoTrivyVersion)
	c.WriteString("jobs:\n")

	c.WriteString("  secrets:\n    name: Secrets (gitleaks)\n    runs-on: docker\n    steps:\n")
	c.WriteString("      - uses: actions/checkout@v4\n        with:\n          fetch-depth: 0\n")
	c.WriteString("      - name: Install gitleaks\n        run: |\n")
	c.WriteString("          curl -sSfL \"https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}/gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz\" | tar -xz -C /usr/local/bin gitleaks\n")
	c.WriteString("      - name: Scan history for secrets\n        run: gitleaks git --redact --no-banner --exit-code 1 .\n\n")

	c.WriteString("  quality:\n    name: Lint, types and tests\n    runs-on: docker\n")
	if o.Dir != "" && o.Dir != "." {
		fmt.Fprintf(&c, "    defaults:\n      run:\n        working-directory: %s\n", o.Dir)
	}
	c.WriteString("    steps:\n      - uses: actions/checkout@v4\n")
	for _, s := range st.Setup {
		c.WriteString(s + "\n")
	}
	for _, s := range st.Run {
		c.WriteString(s + "\n")
	}

	c.WriteString("\n  semgrep:\n    name: SAST (semgrep)\n    runs-on: docker\n    steps:\n      - uses: actions/checkout@v4\n")
	c.WriteString("      - uses: actions/setup-python@v5\n        with:\n          python-version: '3.12'\n")
	c.WriteString("      - name: Install semgrep\n        run: pip install \"semgrep==${SEMGREP_VERSION}\"\n")
	c.WriteString("      - name: Scan\n        run: semgrep scan --config p/ci --error --metrics=off\n\n")

	c.WriteString("  osv:\n    name: Dependencies (osv-scanner)\n    runs-on: docker\n    steps:\n      - uses: actions/checkout@v4\n")
	c.WriteString("      - name: Install osv-scanner\n        run: |\n")
	c.WriteString("          curl -sSfL -o /usr/local/bin/osv-scanner \"https://github.com/google/osv-scanner/releases/download/v${OSV_SCANNER_VERSION}/osv-scanner_linux_amd64\"\n")
	c.WriteString("          chmod +x /usr/local/bin/osv-scanner\n")
	c.WriteString("      - name: Scan lockfiles\n        run: osv-scanner scan -r .\n\n")

	c.WriteString("  trivy:\n    name: Repository scan (trivy)\n    runs-on: docker\n    steps:\n      - uses: actions/checkout@v4\n")
	c.WriteString("      - name: Install trivy\n        run: |\n")
	c.WriteString("          curl -sSfL \"https://github.com/aquasecurity/trivy/releases/download/v${TRIVY_VERSION}/trivy_${TRIVY_VERSION}_Linux-64bit.tar.gz\" | tar -xz -C /usr/local/bin trivy\n")
	c.WriteString("      - name: Scan repository (vulnerabilities, secrets, misconfiguration)\n")
	c.WriteString("        run: trivy fs --scanners vuln,secret,misconfig --severity HIGH,CRITICAL --ignore-unfixed --exit-code 1 .\n")

	var d strings.Builder
	d.WriteString("# Generated by `capsule ci init --provider forgejo`. Deploys to Capsule on push to the production branch.\n")
	d.WriteString("# Protect the branch and require the CI workflow checks before merging: this workflow does not wait for them.\n")
	d.WriteString("# Secrets (repository settings > Actions > Secrets): CAPSULE_TOKEN (deploy-scoped), CAPSULE_ORG_ID, CAPSULE_PROJECT_ID\n")
	d.WriteString("# Variable: CAPSULE_API_URL\n")
	fmt.Fprintf(&d, "name: Deploy\n\non:\n  push:\n    branches: [%s]\n  workflow_dispatch:\n\n", o.Branch)
	d.WriteString("concurrency:\n  group: capsule-deploy\n  cancel-in-progress: false\n\n")
	d.WriteString("jobs:\n  deploy:\n    name: Deploy to Capsule\n    runs-on: docker\n    steps:\n")
	d.WriteString("      - uses: actions/checkout@v4\n")
	d.WriteString("      - uses: actions/setup-node@v4\n        with:\n          node-version: '20'\n")
	fmt.Fprintf(&d, "      - name: Install the Capsule CLI\n        run: npm install -g @kyntocg/capsule-cli@%s   # pinned CLI version\n", capsuleCLIVersion)
	d.WriteString("      - name: Deploy\n")
	d.WriteString("        env:\n          CAPSULE_TOKEN: ${{ secrets.CAPSULE_TOKEN }}\n          CAPSULE_ORG_ID: ${{ secrets.CAPSULE_ORG_ID }}\n          CAPSULE_PROJECT_ID: ${{ secrets.CAPSULE_PROJECT_ID }}\n          CAPSULE_API_URL: ${{ vars.CAPSULE_API_URL }}\n          CAPSULE_CI: \"1\"\n")
	if o.Dir != "" && o.Dir != "." {
		fmt.Fprintf(&d, "        working-directory: %s\n", o.Dir)
	}
	d.WriteString("        run: capsule deploy --yes --ref \"${{ github.ref_name }}\" --sha \"${{ github.sha }}\"\n")
	return forgejoFiles{CI: c.String(), Deploy: d.String()}
}

// capsuleCLIVersion is the npm version the generated deploy job installs.
const capsuleCLIVersion = "0.6.0"

func ciInitForgejo(cmd *cobra.Command, stack, branch, sub string, force, toStdout bool, root string) error {
	if ss, _ := cmd.Flags().GetBool("set-secrets"); ss {
		return fmt.Errorf("--set-secrets only supports github; for Forgejo create a deploy token (capsule tokens create --scope deploy --project <id>) and set the secrets CAPSULE_TOKEN, CAPSULE_ORG_ID, CAPSULE_PROJECT_ID and the variable CAPSULE_API_URL in the repository settings")
	}
	appDir := root
	if sub != "" {
		appDir = root + "/" + sub
	}
	st := detectCIStack(appDir, sub, stack)
	files := generateForgejo(st, ciOptions{Branch: branch, Dir: sub})
	if toStdout {
		fmt.Print("# ---- .forgejo/workflows/ci.yml ----\n" + files.CI + "\n# ---- .forgejo/workflows/deploy.yml ----\n" + files.Deploy)
		return nil
	}
	outDir := root + "/.forgejo/workflows"
	for _, f := range []struct{ name, content string }{{"ci.yml", files.CI}, {"deploy.yml", files.Deploy}} {
		if fileExists(outDir+"/"+f.name) && !force {
			return fmt.Errorf("%s/%s already exists (use --force to overwrite, or --print to preview)", outDir, f.name)
		}
	}
	if err := mkdirWrite(outDir, files); err != nil {
		return err
	}
	fmt.Printf("Detected stack: %s\nWrote .forgejo/workflows/ci.yml and .forgejo/workflows/deploy.yml\n", st.Name)
	for _, n := range st.Notes {
		fmt.Printf("  note: %s\n", n)
	}
	fmt.Println("  note: CodeQL and Dependabot do not exist on Forgejo: Semgrep (SAST) and Renovate (update PRs) replace them.")
	fmt.Println("  note: tool versions are pinned in the env block of ci.yml; the deploy job installs @kyntocg/capsule-cli@" + capsuleCLIVersion + ".")
	fmt.Println("  note: runners need the label \"docker\" (edit runs-on if yours differ); the deploy job does not wait for ci, protect the branch instead.")
	fmt.Println("\nNext steps:")
	fmt.Println("  1. capsule tokens create --name forgejo-ci --scope deploy --project <project-id>")
	fmt.Println("  2. Repository settings > Actions: secrets CAPSULE_TOKEN, CAPSULE_ORG_ID, CAPSULE_PROJECT_ID; variable CAPSULE_API_URL")
	fmt.Println("  3. Commit and push .forgejo/")
	return nil
}

func mkdirWrite(outDir string, files forgejoFiles) error {
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return fmt.Errorf("creating %s: %w", outDir, err)
	}
	for name, content := range map[string]string{"ci.yml": files.CI, "deploy.yml": files.Deploy} {
		if err := os.WriteFile(outDir+"/"+name, []byte(content), 0644); err != nil {
			return fmt.Errorf("writing %s: %w", name, err)
		}
	}
	return nil
}
